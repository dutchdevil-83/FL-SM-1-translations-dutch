function Write-Status {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Message,

        [Parameter()]
        [ValidateSet('Info', 'Success', 'Warning')]
        [string]$Level = 'Info'
    )

    $prefix = switch ($Level) {
