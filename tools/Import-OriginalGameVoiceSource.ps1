#requires -Version 7.2
<#
.SYNOPSIS
Scans an original English Ren'Py game folder, imports only source-like files needed
for voice work, and opens a draft GitHub pull request for review.

Script name: Import-OriginalGameVoiceSource.ps1
Version: 202609.26
Author: Marco's Copilot

.DESCRIPTION
The script is intended to run on the Windows developer machine that contains the
original game files. It uses a Windows folder picker unless -GamePath is supplied.

It copies source-like text files from the selected game folder into
original-source/game while excluding Ren'Py translations, caches, saves, compiled
files, media, archives, and executables. It also creates a SHA-256 manifest and an
import report, creates a dedicated Git branch, commits the snapshot, pushes it, and
opens a draft pull request against the English voice branch.

No Gemini or other AI API calls are made by this script.

.PARAMETER GamePath
Path to the game installation root or directly to its game folder. Defaults to
E:\Games\Fetish Locator SM Studio. If the configured path is unavailable, a Windows
folder picker is shown.

.PARAMETER RepositoryPath
Path to the primary local clone of this repository. Defaults to X:\dev\repos\personal\FL-SM-1-translations-dutch. The script auto-detects the worktree that has the English voice branch checked out.

.PARAMETER BaseBranch
Git branch that receives the source-import pull request.

.PARAMETER BranchName
Optional explicit import branch. A timestamped branch name is generated by default.

.PARAMETER DestinationRelativePath
Repository-relative folder used for the imported source snapshot.

.PARAMETER SkipPush
Create the local branch and commit but do not push it.

.PARAMETER SkipPullRequest
Push the branch but do not create a draft pull request.

.PARAMETER AllowPotentialSecrets
Continue when the conservative secret-pattern scan finds a possible credential.
The scan never prints the suspected secret value.

.EXAMPLE
.\tools\Import-OriginalGameVoiceSource.ps1

.EXAMPLE
.\tools\Import-OriginalGameVoiceSource.ps1 -GamePath 'D:\Games\Fetish Locator S&M Studio'
#>

